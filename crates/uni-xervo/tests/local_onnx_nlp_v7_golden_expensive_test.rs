fn load_fixtures() -> Vec<(String, Value)> {
    let dir = fixture_dir();
    let mut out: Vec<(String, Value)> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("read {}: {e}", dir.display()))
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .filter(|p| p.file_name().is_some_and(|n| n != PROVENANCE_FILE))
        .map(|p| {
            let name = p.file_name().unwrap().to_string_lossy().to_string();
            let bytes = std::fs::read(&p).expect("read fixture");
            (name, serde_json::from_slice(&bytes).expect("parse fixture"))
        })
        .collect();
    out.sort_by(|a, b| a.0.cmp(&b.0));
    assert!(!out.is_empty(), "no fixtures in {}", dir.display());
    out
}

fn str_list(v: &Value) -> Vec<String> {
    v.as_array()
        .map(|a| {
            a.iter()
                .map(|x| x.as_str().unwrap_or_default().to_string())
                .collect()
        })
        .unwrap_or_default()
}

/// `[label, start, end]` triples, as the reference emits NER and SRL spans.
fn span_triples(v: &Value) -> Vec<(String, u64, u64)> {
    v.as_array()
        .map(|a| {
            a.iter()
                .map(|x| {
                    (
                        x[0].as_str().unwrap_or_default().to_string(),
                        x[1].as_u64().unwrap_or_default(),
                        x[2].as_u64().unwrap_or_default(),
                    )
                })
                .collect()
        })
        .unwrap_or_default()
}

/// The discrete decisions compared against the reference, and the ones
/// that differed.
#[derive(Debug, Default)]
struct Tally {
    compared: usize,
    mismatches: Vec<String>,
    /// The largest fact margin difference seen, within tolerance or not.
    max_margin_diff: f32,
}

impl Tally {
    /// Count one decision, recording it when `rust` is not `reference`.
    fn check<T: PartialEq + std::fmt::Debug>(&mut self, at: &str, reference: T, rust: T) {
        self.compared += 1;
        if reference != rust {
            self.mismatches
                .push(format!("{at}: reference {reference:?}, rust {rust:?}"));
        }
    }

    /// Count one fact margin, which may differ by [`MARGIN_TOLERANCE`].
    fn check_margin(&mut self, at: &str, reference: f32, rust: f32) {
        self.compared += 1;
        self.max_margin_diff = self.max_margin_diff.max((reference - rust).abs());
        if (reference - rust).abs() > MARGIN_TOLERANCE {
            self.mismatches
                .push(format!("{at}: margin reference {reference}, rust {rust}"));
        }
    }

    /// The fraction of decisions that differed.
    fn rate(&self) -> f64 {
        if self.compared == 0 {
            0.0
        } else {
            self.mismatches.len() as f64 / self.compared as f64
        }
    }
}

/// Compare one window: structure is asserted, decisions are tallied.
///
/// # Panics
///
/// When the window's structure differs from the reference's: tokens, the
/// analysed word count, sentence spans and speakers, or the word count.
fn compare_window(case: &str, index: usize, expected: &Value, got: &NlpWindow, tally: &mut Tally) {
    let at = format!("{case} window {index}");

    // Structure: what the decoding works on. It does not depend on scores,
    // so it must match exactly in every mode.
    assert_eq!(str_list(&expected["tokens"]), got.tokens, "{at}: tokens");
    assert_eq!(
        expected["analysed_words"].as_u64().unwrap() as usize,
        got.analysed_words,
        "{at}: analysed_words"
    );
    let sentences = expected["sentences"].as_array().expect("sentences");
    assert_eq!(sentences.len(), got.sentences.len(), "{at}: sentence count");
    for (j, (e, g)) in sentences.iter().zip(&got.sentences).enumerate() {
        assert_eq!(
            e["start"].as_u64().unwrap() as usize,
            g.start,
            "{at}: s{j} start"
        );
        assert_eq!(e["end"].as_u64().unwrap() as usize, g.end, "{at}: s{j} end");
        assert_eq!(
            e.get("speaker").and_then(Value::as_str),
            g.speaker.as_deref(),
            "{at}: s{j} speaker"
        );
    }
    let words = expected.get("words").and_then(Value::as_array);
    if let Some(words) = words {
        assert_eq!(words.len(), got.words.len(), "{at}: word count");
    }

    // Per-sentence dialogue acts and sentiment.
    if let Some(layers) = expected.get("sentence_layers").and_then(Value::as_array) {
        for (j, (e, g)) in layers.iter().zip(&got.sentences).enumerate() {
            let s = format!("{at}: s{j}");
            tally.check(&format!("{s} cls"), str_list(&e["cls"]), g.cls.clone());
            tally.check(
                &format!("{s} sentiment"),
                e["sentiment"].as_str(),
                g.sentiment.as_deref(),
            );
            tally.check(
                &format!("{s} whole"),
                e["whole"].as_bool().unwrap(),
                g.whole,
            );
        }
    }

    // Per-word POS, morphology, lemma, head and relation.
    if let Some(words) = words {
        for (i, (e, g)) in words.iter().zip(&got.words).enumerate() {
            let w = format!("{at}: word {i} ({:?})", got.tokens.get(i));
            tally.check(&format!("{w} pos"), e["pos"].as_str(), g.pos.as_deref());
            tally.check(
                &format!("{w} morph"),
                e["morph"].as_str(),
                g.morph.as_deref(),
            );
            tally.check(
                &format!("{w} lemma"),
                e["lemma"].as_str(),
                g.lemma.as_deref(),
            );
            tally.check(
                &format!("{w} head"),
                Some(e["head"].as_u64().unwrap() as usize),
                g.head,
            );
            tally.check(
                &format!("{w} deprel"),
                e["deprel"].as_str(),
                g.deprel.as_deref(),
            );
        }
    }

    // Named entities, as one decision per window.
    if expected.get("ner").is_some() {
        let have: Vec<(String, u64, u64)> = got
            .ner
            .iter()
            .map(|s| (s.label.clone(), s.start as u64, s.end as u64))
            .collect();
        tally.check(&format!("{at}: ner"), span_triples(&expected["ner"]), have);
    }

    // Semantic roles: one frame per predicate, in predicate order.
    if let Some(srl) = expected.get("srl").and_then(Value::as_array) {
        let want: Vec<u64> = srl
            .iter()
            .map(|e| e["predicate"].as_u64().unwrap())
            .collect();
        let have: Vec<u64> = got.srl.iter().map(|g| g.predicate as u64).collect();
        let same_frames = want == have;
        tally.check(&format!("{at}: predicates"), want, have);
        if same_frames {
            for (e, g) in srl.iter().zip(&got.srl) {
                let have: Vec<(String, u64, u64)> = g
                    .args
                    .iter()
                    .map(|a| (a.label.clone(), a.start as u64, a.end as u64))
                    .collect();
                tally.check(
                    &format!("{at}: frame at {} args", g.predicate),
                    span_triples(&e["args"]),
                    have,
                );
            }
        }
    }

    // Coreference clusters of inclusive word spans, as one decision.
    if let Some(coref) = expected.get("coref").and_then(Value::as_array) {
        let want: Vec<Vec<(u64, u64)>> = coref
            .iter()
            .map(|c| {
                c.as_array()
                    .unwrap()
                    .iter()
                    .map(|m| (m[0].as_u64().unwrap(), m[1].as_u64().unwrap()))
                    .collect()
            })
            .collect();
        let have: Vec<Vec<(u64, u64)>> = got
            .coref
            .iter()
            .map(|c| c.iter().map(|&(a, b)| (a as u64, b as u64)).collect())
            .collect();
        tally.check(&format!("{at}: coref"), want, have);
    }

    // Entities, including the conversation's speakers. A different count
    // misaligns everything after it, so it is one decision and the per-entity
    // fields are compared only when the counts agree.
    let entities = expected["entities"].as_array().expect("entities");
    let want: Vec<&str> = entities
        .iter()
        .map(|e| e["text"].as_str().unwrap_or_default())
        .collect();
    let have: Vec<&str> = got.entities.iter().map(|e| e.text.as_str()).collect();
    let same_count = want.len() == have.len();
    if !same_count {
        tally.check(&format!("{at}: entities"), want, have);
    } else {
        for (k, (e, g)) in entities.iter().zip(&got.entities).enumerate() {
            let w = format!("{at}: entity {k}");
            tally.check(
                &format!("{w} type"),
                e["type"].as_str().unwrap(),
                g.ty.as_str(),
            );
            tally.check(
                &format!("{w} text"),
                e["text"].as_str().unwrap(),
                g.text.as_str(),
            );
            tally.check(
                &format!("{w} speaker"),
                e.get("speaker").and_then(Value::as_bool).unwrap_or(false),
                g.speaker,
            );
            if let Some(mentions) = e.get("mentions") {
                tally.check(
                    &format!("{w} mentions"),
                    str_list(mentions),
                    g.mentions.clone(),
                );
            }
            if let Some(spans) = e.get("spans").and_then(Value::as_array) {
                let want: Vec<(u64, u64)> = spans
                    .iter()
                    .map(|s| (s[0].as_u64().unwrap(), s[1].as_u64().unwrap()))
                    .collect();
                let have: Vec<(u64, u64)> =
                    g.spans.iter().map(|&(a, b)| (a as u64, b as u64)).collect();
                tally.check(&format!("{w} spans"), want, have);
            }
        }
    }

    // Facts, in the reference's emission order, with their attributes; the
    // same rule as entities for a different count.
    let facts = expected["facts"].as_array().expect("facts");
    let want: Vec<String> = facts
        .iter()
        .map(|f| {
            format!(
                "{}-{}->{}",
                f["head"].as_u64().unwrap(),
                f["relation"].as_str().unwrap(),
                f["tail"].as_u64().unwrap()
            )
        })
        .collect();
    let have: Vec<String> = got
        .facts
        .iter()
        .map(|f| format!("{}-{}->{}", f.head, f.relation, f.tail))
        .collect();
    for (k, g) in got.facts.iter().enumerate() {
        // Not a comparison: the provider must never report a fact it scored
        // at or below zero, whatever the reference did.
        assert!(
            g.margin > 0.0,
            "{at}: fact {k} margin must be positive to be reported"
        );
    }
    if want != have {
        tally.check(&format!("{at}: facts"), want, have);
        return;
    }
    tally.compared += facts.len();
    for (k, (e, g)) in facts.iter().zip(&got.facts).enumerate() {
        let w = format!("{at}: fact {k}");
        tally.check(
            &format!("{w} polarity"),
            e["polarity"].as_str().unwrap(),
            g.polarity.as_str(),
        );
        tally.check(
            &format!("{w} modality"),
            e["modality"].as_str().unwrap(),
            g.modality.as_str(),
        );
        tally.check(
            &format!("{w} holder"),
            e["holder"].as_u64().map(|v| v as usize),
            g.holder,
        );
        tally.check(
            &format!("{w} time"),
            e["time"].as_u64().map(|v| v as usize),
            g.time,
        );
        tally.check_margin(&w, e["margin"].as_f64().unwrap() as f32, g.margin);
    }
}

#[tokio::test(flavor = "multi_thread")]
async fn rust_pipeline_matches_the_python_reference() {
    require_expensive!();
    let prov = provenance();
    let (exact, why) = comparison_mode(&prov);
    eprintln!(
        "golden comparison: {} ({why}); goldens from {}@{}, ONNX Runtime {} on {}",
        if exact { "exact" } else { "tolerant" },
        prov.repo,
        prov.revision,
        prov.onnxruntime,
        prov.platform
    );
    let runtime = runtime_with_threads(exact.then_some(prov.intra_op_threads)).await;
    let model = runtime.nlp_model("nlp/kniv-v7").await.expect("resolve nlp");
    let schema = memory_schema();
    let mut tally = Tally::default();

    for (name, fixture) in load_fixtures() {
        let case = fixture["case"].as_str().unwrap_or(&name).to_string();
        let input = &fixture["input"];
        let tasks = NlpTasks::ALL;
        let with_schema = fixture["schema"].as_str().is_some();

        // Turns and prose are two different entry points into the window
        // builder, and the conversation path is the one uniko uses.
        let turn_values: Vec<(String, String)> = input
            .get("turns")
            .and_then(Value::as_array)
            .map(|a| {
                a.iter()
                    .map(|t| {
                        (
                            t[0].as_str().unwrap().to_string(),
                            t[1].as_str().unwrap().to_string(),
                        )
                    })
                    .collect()
            })
            .unwrap_or_default();
        let turns: Vec<Turn<'_>> = turn_values
            .iter()
            .map(|(s, t)| Turn::new(s.as_str(), t.as_str()))
            .collect();
        let text = input.get("text").and_then(Value::as_str).unwrap_or("");

        let mut request = if turns.is_empty() {
            NlpRequest::new(text, tasks)
        } else {
            NlpRequest::from_turns(&turns, tasks)
        };
        if with_schema {
            request = request.with_schema(&schema);
        }

        let result = &model.analyze(vec![request]).await.expect("analyze")[0];
        let expected = fixture["windows"].as_array().expect("windows");
        assert_eq!(expected.len(), result.windows.len(), "{case}: window count");
        let before = tally.mismatches.len();
        for (i, (e, g)) in expected.iter().zip(&result.windows).enumerate() {
            compare_window(&case, i, e, g, &mut tally);
        }
        eprintln!(
            "{case}: {} window(s), {} decision(s) differ",
            result.windows.len(),
            tally.mismatches.len() - before
        );
    }

    for m in &tally.mismatches {
        eprintln!("  differs: {m}");
    }
    eprintln!(
        "{} of {} decisions differ ({:.2}%); largest fact margin difference {:.1e}",
        tally.mismatches.len(),
        tally.compared,
        100.0 * tally.rate(),
        tally.max_margin_diff
    );
    if exact {
        assert!(
            tally.mismatches.is_empty(),
            "exact mode: on the goldens' own ONNX Runtime library every decision must match"
        );
    } else {
        assert!(
            tally.rate() <= MISMATCH_BUDGET,
            "{:.2}% of decisions differ, above the {:.1}% budget for another ONNX Runtime build",
            100.0 * tally.rate(),
            100.0 * MISMATCH_BUDGET
        );
    }
}

/// The smoke assertion from the support specification: the quick-start
/// conversation must place the speaker in Lisbon and at a bank.
#[tokio::test(flavor = "multi_thread")]
async fn quickstart_conversation_extracts_residence_and_employer() {
    require_expensive!();
    let runtime = runtime().await;
    let model = runtime.nlp_model("nlp/kniv-v7").await.expect("resolve nlp");

    let schema = ExtractionSchema {
        relations: vec![
            LabelSpec::described("lives in", "the place where the head resides"),
            LabelSpec::described(
                "employer",
                "person or organization for which the head works or worked",
            ),
        ],
        entity_types: Some(vec![
            LabelSpec::name("location"),
            LabelSpec::name("organization"),
            LabelSpec::name("person"),
        ]),
        top_per_pair: None,
    };
    let turns = [
        Turn::new("user", "I moved to Lisbon last year and started at a bank."),
        Turn::new("assistant", "Congratulations on the move!"),
    ];
    let request = NlpRequest::from_turns(&turns, NlpTasks::FACTS).with_schema(&schema);
    let result = &model.analyze(vec![request]).await.expect("analyze")[0];

    let window = &result.windows[0];
    let by_relation: HashMap<&str, Vec<String>> =
        window.facts.iter().fold(HashMap::new(), |mut acc, f| {
            acc.entry(f.relation.as_str())
                .or_default()
                .push(window.entities[f.tail].text.clone());
            acc
        });
    eprintln!(
        "entities: {:?}",
        window
            .entities
            .iter()
            .map(|e| (e.ty.as_str(), e.text.as_str()))
            .collect::<Vec<_>>()
    );
    eprintln!("facts: {by_relation:?}");

    // The speaker is an entity in its own right, which is what lets a
    // first-person statement be stored about the user.
    assert!(
        window
            .entities
            .iter()
            .any(|e| e.speaker && e.text == "user"),
        "the user must be a speaker entity"
    );
    for (relation, tail) in [("lives in", "Lisbon"), ("employer", "a bank")] {
        let fact = window
            .facts
            .iter()
            .find(|f| f.relation == relation && window.entities[f.tail].text == tail)
            .unwrap_or_else(|| panic!("no '{relation}' fact with tail '{tail}': {by_relation:?}"));
        assert!(
            window.entities[fact.head].speaker,
            "{relation}: head is the speaker"
        );
        assert_eq!(
            fact.polarity,
            uni_xervo::traits::FactPolarity::Positive,
            "{relation}: polarity"
        );
        assert_eq!(
            fact.modality,
            uni_xervo::traits::FactModality::Asserted,
            "{relation}: modality"
        );
        assert_eq!(
            fact.holder.map(|h| window.entities[h].text.clone()),
            Some("user".to_string()),
            "{relation}: holder"
        );
    }
}

/// Task flags gate graph calls, so a narrow request must still produce the
/// same answers for the heads it did ask for.
#[tokio::test(flavor = "multi_thread")]
async fn narrow_task_requests_agree_with_the_full_analysis() {
    require_expensive!();
    let runtime = runtime().await;
    let model = runtime.nlp_model("nlp/kniv-v7").await.expect("resolve nlp");

    let text = "Ada Lovelace was born in London in 1815.";
    let full = &model
        .analyze(vec![NlpRequest::new(text, NlpTasks::ALL)])
        .await
        .expect("analyze")[0];
    let narrow = &model
        .analyze(vec![NlpRequest::new(text, NlpTasks::NER | NlpTasks::POS)])
        .await
        .expect("analyze")[0];

    assert_eq!(full.windows[0].ner, narrow.windows[0].ner);
    assert_eq!(
        full.windows[0]
            .words
            .iter()
            .map(|w| w.pos.clone())
            .collect::<Vec<_>>(),
        narrow.windows[0]
            .words
            .iter()
            .map(|w| w.pos.clone())
            .collect::<Vec<_>>()
    );
    // Unrequested heads stay empty rather than being computed and dropped.
    assert!(narrow.windows[0].srl.is_empty());
    assert!(narrow.windows[0].words.iter().all(|w| w.deprel.is_none()));
    assert!(!full.windows[0].srl.is_empty());

    // The v1-shaped projection is populated for a v7 model too.
    assert!(!narrow.tokens.is_empty());
    assert!(narrow.tokens.iter().all(|t| t.pos.is_some()));
    assert!(!narrow.entities.is_empty(), "BIO-merged entities");
    for token in &narrow.tokens {
        assert_eq!(
            text.get(token.start..token.end),
            Some(token.text.as_str()),
            "byte offsets must index the input"
        );
    }
}

/// The `plain` graph is built at load, so the model reports the execution
/// providers it runs on before any request (rustic-ai/uni-xervo#65). On a
/// CPU-only build that is `["cpu"]`. Needs no golden fixtures, so any v7
/// release works, e.g. `KNIV_V7_MODEL_DIR=dragonscale-ai/kniv-v7-tiny-en`.
#[tokio::test(flavor = "multi_thread")]
async fn reports_execution_providers_from_load() {
    require_expensive!();
    let runtime = runtime().await;
    let model = runtime.nlp_model("nlp/kniv-v7").await.expect("resolve nlp");
    let eps = model.active_execution_providers();
    assert!(eps.contains(&"cpu".to_string()), "{eps:?}");
    #[cfg(not(any(feature = "gpu-cuda", feature = "gpu-metal")))]
    assert_eq!(eps, ["cpu"]);

    // A full request builds the lazy graphs too; they share `plain`'s
    // configuration, so the list does not change.
    model
        .analyze(vec![NlpRequest::new(
            "Ada Lovelace was born in London in 1815.",
            NlpTasks::ALL,
        )])
        .await
        .expect("analyze");
    assert_eq!(model.active_execution_providers(), eps);
}
