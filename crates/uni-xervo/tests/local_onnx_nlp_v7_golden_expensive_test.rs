//! kniv v7 conformance: the Rust provider against the Python reference.
//!
//! The provider in `provider/local_onnx/nlp_v7` is a port of
//! `kniv_v7/runtime.py`, and every decoding step in it — BIO Viterbi,
//! Chu-Liu-Edmonds, predicate-aware SRL, greedy span decoding, calibrated
//! relation margins — is part of the *model's* behaviour rather than an
//! implementation choice. Unit tests pin those algorithms against hand-built
//! matrices; only this test shows that the whole pipeline, wired to real
//! graphs, produces what the reference produces.
//!
//! The fixtures in `tests/fixtures/kniv-v7/<tag>/` are the reference's own
//! output, regenerated by `scripts/gen-kniv-v7-goldens.py`. Each tag pins one
//! encoder at one precision, because quantisation moves scores: an INT8 run is
//! compared against INT8 goldens, never against fp32 ones.
//!
//! ```text
//! # UltraBERT (1,024 subwords, mean pooling) — the default
//! EXPENSIVE_TESTS=1 KNIV_V7_MODEL_DIR=/path/to/kniv-v7-xlarge-u-en \
//!   cargo test --features provider-onnx --test local_onnx_nlp_v7_golden_expensive_test
//!
//! # DeBERTa (512 subwords, first-subword pooling, no `word_end` input)
//! EXPENSIVE_TESTS=1 KNIV_V7_FIXTURE_TAG=deberta-int8 \
//!   KNIV_V7_MODEL_DIR=/path/to/kniv-v7-xlarge-d-en \
//!   cargo test --features provider-onnx --test local_onnx_nlp_v7_golden_expensive_test
//! ```
//!
//! Both encoders are worth running: they differ in window size and in subword
//! pooling, and the pooling difference is a different set of graph inputs.
//! Without `KNIV_V7_MODEL_DIR` the model is taken from the Hugging Face repo
//! matching the selected tag, which is a ~2-3 GB download.

use std::collections::HashMap;
use std::env;

use serde_json::Value;
use uni_xervo::api::{ModelAliasSpec, ModelTask, WarmupPolicy};
use uni_xervo::provider::LocalOnnxProvider;
use uni_xervo::runtime::ModelRuntime;
use uni_xervo::traits::{ExtractionSchema, LabelSpec, NlpRequest, NlpTasks, NlpWindow, Turn};

/// Which committed fixture set to replay, and the repo it was generated
/// from.
const FIXTURE_TAGS: [(&str, &str); 2] = [
    ("ultrabert-int8", "dragonscale-ai/kniv-v7-xlarge-u-en"),
    ("deberta-int8", "dragonscale-ai/kniv-v7-xlarge-d-en"),
];
const DEFAULT_FIXTURE_TAG: &str = "ultrabert-int8";
/// Margins are the one thing compared loosely. Two sources of slack:
/// the reference rounds them to three decimals on the way into its JSON
/// (up to 5e-4), and the INT8 graphs reduce in whatever order each runtime's
/// thread partitioning picks (measured at up to ~1e-3 on these fixtures).
///
/// Everything discrete — every tag, head, span, entity, fact identity,
/// polarity, modality, holder and time — must match exactly, and that is the
/// real conformance claim.
const MARGIN_TOLERANCE: f32 = 2e-3;

fn should_run() -> bool {
    env::var("EXPENSIVE_TESTS").is_ok()
}

macro_rules! require_expensive {
    () => {
        if !should_run() {
            eprintln!("Skipping test - set EXPENSIVE_TESTS=1 to run");
            return;
        }
    };
}

fn fixture_tag() -> String {
    let tag = env::var("KNIV_V7_FIXTURE_TAG").unwrap_or_else(|_| DEFAULT_FIXTURE_TAG.to_string());
    assert!(
        FIXTURE_TAGS.iter().any(|(t, _)| *t == tag),
        "unknown KNIV_V7_FIXTURE_TAG '{tag}'; known tags: {:?}",
        FIXTURE_TAGS.map(|(t, _)| t)
    );
    tag
}

fn fixture_dir() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/kniv-v7")
        .join(fixture_tag())
}

fn model_id() -> String {
    env::var("KNIV_V7_MODEL_DIR").unwrap_or_else(|_| {
        let tag = fixture_tag();
        FIXTURE_TAGS
            .iter()
            .find(|(t, _)| *t == tag)
            .map(|(_, repo)| (*repo).to_string())
            .expect("a known tag has a repo")
    })
}

async fn runtime() -> std::sync::Arc<ModelRuntime> {
    let spec = ModelAliasSpec {
        alias: "nlp/kniv-v7".to_string(),
        task: ModelTask::Nlp,
        provider_id: "local/onnx".to_string(),
        model_id: model_id(),
        revision: None,
        warmup: WarmupPolicy::Lazy,
        required: false,
        timeout: None,
        load_timeout: Some(3600),
        retry: None,
        options: serde_json::json!({
            "variant": "int8,fp16",
            "execution_providers": ["cpu"],
        }),
    };
    ModelRuntime::builder()
        .register_provider(LocalOnnxProvider::new())
        .catalog(vec![spec])
        .build()
        .await
        .expect("build runtime")
}

