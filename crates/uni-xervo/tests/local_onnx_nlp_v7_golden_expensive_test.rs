#![cfg(any(feature = "provider-onnx", feature = "provider-onnx-dynamic"))]

//! kniv v7 conformance: the Rust provider against the Python reference.
//!
//! The provider in `provider/local_onnx/nlp_v7` is a port of
//! `kniv_v7/runtime.py`, and every decoding step in it — BIO Viterbi,
//! Chu-Liu-Edmonds, predicate-aware SRL, greedy span decoding, calibrated
//! relation margins — is part of the *model's* behaviour rather than an
//! implementation choice. Unit tests pin those algorithms against hand-built
//! matrices; only this test shows that the whole pipeline, wired to real
//! graphs, produces what the reference produces.
//!
//! The fixtures in `tests/fixtures/kniv-v7/<tag>/` are the reference's own
//! output, regenerated by `scripts/gen-kniv-v7-goldens.py`. Each tag pins one
//! encoder at one precision, because quantisation moves scores: an INT8 run is
//! compared against INT8 goldens, never against fp32 ones. The tag's
//! `provenance.json` names the model revision the goldens came from, which
//! this test loads from Hugging Face (about 2 GB for UltraBERT, 3.5 GB for
//! DeBERTa, cached after the first run).
//!
//! ```text
//! # UltraBERT (1,024 subwords, mean pooling) — the default
//! EXPENSIVE_TESTS=1 cargo test --features provider-onnx \
//!   --test local_onnx_nlp_v7_golden_expensive_test
//!
//! # DeBERTa (512 subwords, first-subword pooling, no `word_end` input)
//! EXPENSIVE_TESTS=1 KNIV_V7_FIXTURE_TAG=deberta-int8 cargo test --features provider-onnx \
//!   --test local_onnx_nlp_v7_golden_expensive_test
//!
//! # Exact: on the ONNX Runtime library the goldens were generated with
//! EXPENSIVE_TESTS=1 ORT_DYLIB_PATH=/path/to/onnxruntime/capi/libonnxruntime.so.1.31.1 \
//!   cargo test --no-default-features --features provider-onnx-dynamic \
//!   --test local_onnx_nlp_v7_golden_expensive_test
//! ```
//!
//! Both encoders are worth running: they differ in window size and in subword
//! pooling, and the pooling difference is a different set of graph inputs.
//! `KNIV_V7_MODEL_DIR` replaces the pinned model with a local release or
//! another repo, for the model-agnostic tests.
//!
//! # Exact and tolerant comparison
//!
//! INT8 results depend on the ONNX Runtime build, not only on its version:
//! the bundled build and the Python wheel round some shapes differently
//! (both stay as close to the fp32 graph), which flips a decision that sits
//! near a tie. So the golden comparison has two modes:
//!
//! - **exact**, when the library loaded through `ORT_DYLIB_PATH` is the one
//!   in `provenance.json` (by SHA-256) and the model is the pinned revision:
//!   every output must match. Measured: this port and the reference agree
//!   bit for bit on the encoder outputs when they share a library.
//! - **tolerant**, otherwise: structure (windows, tokens, sentences, word
//!   counts) must still match exactly, since it does not depend on scores;
//!   the discrete decisions may differ in at most [`MISMATCH_BUDGET`] of the
//!   comparisons. Every difference is printed in both modes.

