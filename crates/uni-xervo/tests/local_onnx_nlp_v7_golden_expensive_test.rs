/// Which committed fixture set to replay; each directory's `provenance.json`
/// names the repo and revision it was generated from.
const FIXTURE_TAGS: [&str; 2] = ["ultrabert-int8", "deberta-int8"];
const DEFAULT_FIXTURE_TAG: &str = "ultrabert-int8";
/// The generator's record of what produced a tag's goldens.
const PROVENANCE_FILE: &str = "provenance.json";
/// Margins are the one thing compared loosely, even in exact mode. The
/// measured sources of slack:
///
/// - the reference rounds them to three decimals in its JSON (up to 5e-4);
/// - the arithmetic around the graphs (label pooling, the marker inputs,
///   calibration) is the port's own, in its own float order: up to 2.3e-3 on
///   the goldens' library with the same thread count, with every encoder
///   output bit-identical;
/// - INT8 graphs reduce in an order that depends on the thread count: up to
///   4e-3 between one thread and all of them, which is why exact mode pins
///   the goldens' count.
///
/// Everything discrete — every tag, head, span, entity, fact identity,
/// polarity, modality, holder and time — is what the comparison counts.
const MARGIN_TOLERANCE: f32 = 5e-3;
/// The share of discrete decisions that may differ in tolerant mode, on an
/// ONNX Runtime build other than the goldens'.
///
/// Measured on the bundled build (linux-x86_64): 0.24% for UltraBERT and
/// 0.54% for DeBERTa, every one a fact near the threshold or its margin.
/// A port defect moves tags and heads across whole windows, far above this.
const MISMATCH_BUDGET: f64 = 0.02;

fn should_run() -> bool {
    env::var("EXPENSIVE_TESTS").is_ok()
}

macro_rules! require_expensive {
    () => {
        if !should_run() {
            eprintln!("Skipping test - set EXPENSIVE_TESTS=1 to run");
            return;
        }
    };
}

fn fixture_tag() -> String {
    let tag = env::var("KNIV_V7_FIXTURE_TAG").unwrap_or_else(|_| DEFAULT_FIXTURE_TAG.to_string());
    assert!(
        FIXTURE_TAGS.contains(&tag.as_str()),
        "unknown KNIV_V7_FIXTURE_TAG '{tag}'; known tags: {FIXTURE_TAGS:?}"
    );
    tag
}

fn fixture_dir() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/kniv-v7")
        .join(fixture_tag())
}

/// What produced a tag's goldens: `provenance.json`, written by the generator.
#[derive(Debug)]
struct Provenance {
    repo: String,
    revision: String,
    onnxruntime: String,
    library_sha256: String,
    platform: String,
    /// Intra-op threads per session; exact mode runs with the same count.
    intra_op_threads: u64,
}

fn provenance() -> Provenance {
    let path = fixture_dir().join(PROVENANCE_FILE);
    let bytes = std::fs::read(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    let v: Value = serde_json::from_slice(&bytes).expect("parse provenance.json");
    let field = |k: &str| {
        v[k].as_str()
            .unwrap_or_else(|| panic!("provenance.json has no '{k}'"))
            .to_string()
    };
    Provenance {
        repo: field("repo"),
        revision: field("revision"),
        onnxruntime: field("onnxruntime"),
        library_sha256: field("onnxruntime_library_sha256"),
        platform: field("platform"),
        intra_op_threads: v["intra_op_threads"]
            .as_u64()
            .expect("provenance.json has no 'intra_op_threads'"),
    }
}

/// The model to load and the revision to pin: the goldens' own, unless
/// `KNIV_V7_MODEL_DIR` names another release (then unpinned).
fn model_source() -> (String, Option<String>) {
    match env::var("KNIV_V7_MODEL_DIR") {
        Ok(dir) => (dir, None),
        Err(_) => {
            let p = provenance();
            (p.repo, Some(p.revision))
        }
    }
}

/// The comparison mode, and why: exact only on the goldens' own ONNX Runtime
/// library and model revision.
fn comparison_mode(p: &Provenance) -> (bool, String) {
    if env::var_os("KNIV_V7_MODEL_DIR").is_some() {
        return (false, "KNIV_V7_MODEL_DIR replaces the pinned model".into());
    }
    if !cfg!(feature = "provider-onnx-dynamic") {
        return (
            false,
            format!(
                "the bundled ONNX Runtime is not the goldens' {} build ({})",
                p.onnxruntime, p.platform
            ),
        );
    }
    let Some(lib) = env::var_os("ORT_DYLIB_PATH") else {
        return (false, "ORT_DYLIB_PATH is not set".into());
    };
    let bytes = std::fs::read(&lib)
        .unwrap_or_else(|e| panic!("read ORT_DYLIB_PATH {}: {e}", lib.to_string_lossy()));
    let sha = format!("{:x}", sha2::Sha256::digest(&bytes));
    if sha == p.library_sha256 {
        (
            true,
            format!("ORT_DYLIB_PATH is the goldens' library ({})", p.onnxruntime),
        )
    } else {
        (
            false,
            format!(
                "ORT_DYLIB_PATH is not the goldens' ONNX Runtime {} library for {} (sha256 {sha})",
                p.onnxruntime, p.platform
            ),
        )
    }
}

async fn runtime() -> std::sync::Arc<ModelRuntime> {
    runtime_with_threads(None).await
}

/// The runtime, with each session on `threads` intra-op threads when given
/// (exact mode: the reduction order then matches the goldens').
async fn runtime_with_threads(threads: Option<u64>) -> std::sync::Arc<ModelRuntime> {
    let (model_id, revision) = model_source();
    let mut options = serde_json::json!({
        "variant": "int8,fp16",
        "execution_providers": ["cpu"],
    });
    if let Some(n) = threads {
        options["intra_op_num_threads"] = n.into();
        options["inter_op_num_threads"] = 1.into();
    }
    let spec = ModelAliasSpec {
        alias: "nlp/kniv-v7".to_string(),
        task: ModelTask::Nlp,
        provider_id: "local/onnx".to_string(),
        model_id,
        revision,
        warmup: WarmupPolicy::Lazy,
        required: false,
        timeout: None,
        load_timeout: Some(3600),
        retry: None,
        options,
    };
    ModelRuntime::builder()
        .register_provider(LocalOnnxProvider::new())
        .catalog(vec![spec])
        .build()
        .await
        .expect("build runtime")
}

